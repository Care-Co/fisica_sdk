"""Generate public wrapper constants; private algorithms are never copied.

Release versions come from the release manifests. Status, session and entitlement
codes come from the public C header, the single definition every language shares.

    python tools/sync_binding_metadata.py           rewrite the generated files that differ
    python tools/sync_binding_metadata.py --check   write nothing; exit 1 listing the stale ones
"""
import argparse
import json
import re
import sys
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
NOTE='Generated by tools/sync_binding_metadata.py from native/include/fisica_core.h, wrappers/ble-profile.json and wrappers/license-messages.json. Do not edit.'
FLAGS={'FisicaEntitlementWarning','FisicaFeature'}
# Swift reserved words a header member may map to (FisicaTrack EXTENSION); escaped with backticks.
SWIFT_KEYWORDS={'extension','default','case','class','struct','enum','func','import','init','let','var','protocol',
                'return','self','static','subscript','switch','where','while','in','is','as','operator','internal',
                'private','public','repeat','throw','throws','try','catch','defer','do','else','if','for','guard','nil','true','false'}

def header_enums():
    text=(ROOT/'native/include/fisica_core.h').read_text()
    enums={}
    for name,body in re.findall(r'enum\s+(\w+)\s*\{([^}]*)\}',text):
        members=[(key[len('FISICA_'):].split('_'),int(value)) for key,value in re.findall(r'(FISICA_\w+)\s*=\s*(\d+)',body)]
        # Drop the words every member shares (CONTRACT_KIND_NONE -> NONE); keep at least one word.
        while all(len(words)>1 for words,_ in members) and (len(members)==1 or len({words[0] for words,_ in members})==1):
            members=[(words[1:],value) for words,value in members]
        enums[name]=[('_'.join(words),value) for words,value in members]
    return enums

def camel(name,upper=False):
    words=name.lower().split('_')
    return ''.join(w.capitalize() for w in words) if upper else words[0]+''.join(w.capitalize() for w in words[1:])

def ble():
    return json.loads((ROOT/'wrappers/ble-profile.json').read_text())

def messages(enums):
    """License messages by header member: (reason member, full text) and (warning member, text)."""
    data=json.loads((ROOT/'wrappers/license-messages.json').read_text())
    reasons=[(m,data['reasons'][m.lower()]+' '+data['basic_mode']) for m,_ in enums['FisicaModeReason'] if m!='NONE']
    warnings=[(m,data['warnings'][m.lower()]) for m,_ in enums['FisicaEntitlementWarning']]
    return data['basic_mode'],reasons,warnings

def quoted(text):
    return json.dumps(text,ensure_ascii=False).replace('$','\\$')

def swift_name(name):
    return f'`{name}`' if name in SWIFT_KEYWORDS else name

def swift(enums,profile):
    out=f'// {NOTE}\n'
    for name,members in enums.items():
        out+=f'public enum {name}: UInt32, CaseIterable {{\n'+''.join(f'    case {swift_name(camel(m))} = {v}\n' for m,v in members)+'}\n'
    out+='/// GATT characteristics used by the Scale. `verified` is false until confirmed on production firmware.\n'
    out+='public struct FisicaBleProfile: Equatable {\n    public let write: String, notify: String\n    public init(write: String, notify: String) { self.write = write; self.notify = notify }\n'
    out+=''.join(f'    public static let {camel(p["name"])} = FisicaBleProfile(write: "{p["write"]}", notify: "{p["notify"]}")\n' for p in profile['profiles'])
    out+='    public static let known: [FisicaBleProfile] = ['+', '.join('.'+camel(p['name']) for p in profile['profiles'])+']\n'
    out+=f'    public static let nameContains = "{profile["name_contains"]}"\n    public static let verified = {str(profile["verified"]).lower()}\n}}\n'
    basic,reasons,warnings=messages(enums)
    out+='public extension FisicaModeReason {\n    /// Why the SDK is in basic mode and what to do; nil for `.none` (full mode).\n    var message: String? {\n        switch self {\n        case .none: return nil\n'
    out+=''.join(f'        case .{swift_name(camel(m))}: return {json.dumps(t,ensure_ascii=False)}\n' for m,t in reasons)+'        }\n    }\n}\n'
    out+='public extension FisicaEntitlementWarning {\n    var message: String {\n        switch self {\n'
    out+=''.join(f'        case .{swift_name(camel(m))}: return {json.dumps(t,ensure_ascii=False)}\n' for m,t in warnings)+'        }\n    }\n}\n'
    return out

def kotlin(enums,profile):
    out=f'// {NOTE}\npackage com.carenco.fisica\n'
    for name,members in enums.items():
        out+=f'object {name} {{\n'+''.join(f'    const val {m} = {v}\n' for m,v in members)+'}\n'
    out+='/** GATT characteristics used by the Scale. VERIFIED is false until confirmed on production firmware. */\n'
    out+='data class FisicaBleProfile(val write: String, val notify: String) {\n    companion object {\n'
    out+=''.join(f'        @JvmField val {p["name"].upper()} = FisicaBleProfile("{p["write"]}", "{p["notify"]}")\n' for p in profile['profiles'])
    out+='        @JvmField val KNOWN = listOf('+', '.join(p['name'].upper() for p in profile['profiles'])+')\n'
    out+=f'        const val NAME_CONTAINS = "{profile["name_contains"]}"\n        const val VERIFIED = {str(profile["verified"]).lower()}\n    }}\n}}\n'
    basic,reasons,warnings=messages(enums)
    out+='/** License messages: why the SDK is in basic mode (by FisicaModeReason) and each FisicaEntitlementWarning bit. */\n'
    out+=f'object FisicaLicenseMessages {{\n    const val BASIC_MODE = {quoted(basic)}\n'
    out+='    @JvmField val REASONS: Map<Int, String> = mapOf(\n'+''.join(f'        FisicaModeReason.{m} to {quoted(t)},\n' for m,t in reasons)+'    )\n'
    out+='    @JvmField val WARNINGS: Map<Int, String> = linkedMapOf(\n'+''.join(f'        FisicaEntitlementWarning.{m} to {quoted(t)},\n' for m,t in warnings)+'    )\n}\n'
    return out

def dotnet(enums,profile):
    out=f'// {NOTE}\nnamespace CareCo.Fisica;\n'
    for name,members in enums.items():
        out+=('[System.Flags] ' if name in FLAGS else '')+f'public enum {name} : uint {{ '+', '.join(f'{camel(m,True)} = {v}' for m,v in members)+' }\n'
    out+='/// <summary>GATT characteristics used by the Scale. Verified is false until confirmed on production firmware.</summary>\n'
    out+='public sealed record FisicaBleProfile(string Write, string Notify) {\n'
    out+=''.join(f'    public static readonly FisicaBleProfile {camel(p["name"],True)} = new("{p["write"]}", "{p["notify"]}");\n' for p in profile['profiles'])
    out+='    public static readonly IReadOnlyList<FisicaBleProfile> Known = ['+', '.join(camel(p['name'],True) for p in profile['profiles'])+'];\n'
    out+=f'    public const string NameContains = "{profile["name_contains"]}";\n    public const bool Verified = {str(profile["verified"]).lower()};\n}}\n'
    basic,reasons,warnings=messages(enums)
    out+='/// <summary>License messages: why the SDK is in basic mode and what each warning means.</summary>\n'
    out+=f'public static class FisicaLicenseMessages {{\n    public const string BasicMode = {json.dumps(basic,ensure_ascii=False)};\n'
    out+='    public static string? Reason(FisicaModeReason reason) => reason switch {\n'+''.join(f'        FisicaModeReason.{camel(m,True)} => {json.dumps(t,ensure_ascii=False)},\n' for m,t in reasons)+'        _ => null,\n    };\n'
    out+='    /// <summary>The message of one warning bit; "" for no bit or several (Warnings lists each).</summary>\n'
    out+='    public static string Warning(FisicaEntitlementWarning warning) => warning switch {\n'+''.join(f'        FisicaEntitlementWarning.{camel(m,True)} => {json.dumps(t,ensure_ascii=False)},\n' for m,t in warnings)+'        _ => "",\n    };\n'
    out+='    /// <summary>A message for each bit raised in warnings (as the Warning event passes them), in bit order.</summary>\n'
    out+='    public static IReadOnlyList<string> Warnings(FisicaEntitlementWarning warnings) =>\n'
    out+='        Enum.GetValues<FisicaEntitlementWarning>().Where(bit => (warnings & bit)!=0).Select(Warning).ToArray();\n}\n'
    return out

def dart(enums,profile):
    out=f"// {NOTE}\npart of '../fisica_core.dart';\n"
    # The Dart event object already owns the name FisicaSessionEvent.
    renamed={'FisicaSessionEvent':'FisicaSessionEventKind'}
    for name,members in enums.items():
        out+=f'abstract final class {renamed.get(name,name)} {{\n'+''.join(f'  static const {camel(m)} = {v};\n' for m,v in members)+'}\n'
    out+='/// GATT characteristics used by the Scale. `verified` is false until confirmed on production firmware.\n'
    out+='class FisicaBleProfile {\n  final String write, notify;\n  const FisicaBleProfile(this.write, this.notify);\n'
    out+=''.join(f"  static const {camel(p['name'])} = FisicaBleProfile('{p['write']}', '{p['notify']}');\n" for p in profile['profiles'])
    out+='  static const known = ['+', '.join(camel(p['name']) for p in profile['profiles'])+'];\n'
    out+=f"  static const nameContains = '{profile['name_contains']}';\n  static const verified = {str(profile['verified']).lower()};\n}}\n"
    basic,reasons,warnings=messages(enums)
    out+='/// Why the SDK is in basic mode, by [FisicaModeReason], and what each [FisicaEntitlementWarning] bit means.\n'
    out+=f'const fisicaLicenseBasicMode = {quoted(basic)};\n'
    out+='const fisicaReasonMessages = <int, String>{\n'+''.join(f'  FisicaModeReason.{camel(m)}: {quoted(t)},\n' for m,t in reasons)+'};\n'
    out+='const fisicaWarningMessages = <int, String>{\n'+''.join(f'  FisicaEntitlementWarning.{camel(m)}: {quoted(t)},\n' for m,t in warnings)+'};\n'
    return out

def python(enums,profile):
    out=f'"""{NOTE}"""\nfrom enum import IntEnum, IntFlag\n'
    for name,members in enums.items():
        out+=f'\n\nclass {name}({"IntFlag" if name in FLAGS else "IntEnum"}):\n'+''.join(f'    {m} = {v}\n' for m,v in members)
    out+='\n\n# GATT characteristics used by the Scale. BLE_PROFILE_VERIFIED stays False until confirmed on production firmware.\n'
    out+='BLE_PROFILES = {\n'+''.join(f"    '{p['name']}': {{'write': '{p['write']}', 'notify': '{p['notify']}'}},\n" for p in profile['profiles'])+'}\n'
    out+=f"BLE_NAME_CONTAINS = '{profile['name_contains']}'\nBLE_PROFILE_VERIFIED = {profile['verified']}\n"
    basic,reasons,warnings=messages(enums)
    out+='\n# License messages: why the SDK is in basic mode (by reason name) and each warning.\n'
    out+=f'LICENSE_BASIC_MODE = {basic!r}\n'
    out+='LICENSE_REASON_MESSAGES = {\n'+''.join(f'    {m.lower()!r}: {t!r},\n' for m,t in reasons)+'}\n'
    out+='LICENSE_WARNING_MESSAGES = {\n'+''.join(f'    {m.lower()!r}: {t!r},\n' for m,t in warnings)+'}\n'
    return out

def generated():
    sdk=json.loads((ROOT/'sdk-release.json').read_text())['sdk_version']
    version=lambda name: json.loads((ROOT/'wrappers'/name/'wrapper.json').read_text())['version']
    enums,profile=header_enums(),ble()
    return {
        ROOT/'wrappers/swift/Sources/FisicaScale/Release.swift': f'// Generated by tools/sync_binding_metadata.py\npublic enum FisicaRelease {{ public static let sdkVersion = "{sdk}"; public static let wrapperVersion = "{version("swift")}" }}\n',
        ROOT/'wrappers/kotlin/src/main/kotlin/com/carenco/fisica/Release.kt': f'// Generated by tools/sync_binding_metadata.py\npackage com.carenco.fisica\nobject FisicaRelease {{ const val SDK_VERSION = "{sdk}"; const val WRAPPER_VERSION = "{version("kotlin")}" }}\n',
        ROOT/'wrappers/dotnet/Release.cs': f'// Generated by tools/sync_binding_metadata.py\nnamespace CareCo.Fisica;\npublic static class FisicaRelease {{ public const string SdkVersion = "{sdk}"; public const string WrapperVersion = "{version("dotnet")}"; }}\n',
        ROOT/'wrappers/swift/Sources/FisicaScale/Codes.swift': swift(enums,profile),
        ROOT/'wrappers/kotlin/src/main/kotlin/com/carenco/fisica/Codes.kt': kotlin(enums,profile),
        ROOT/'wrappers/dotnet/Codes.cs': dotnet(enums,profile),
        ROOT/'wrappers/flutter/lib/src/codes.dart': dart(enums,profile),
        ROOT/'fisica_sdk/codes.py': python(enums,profile),
    }

def retained_symbols():
    # Static Apple builds keep every public C function alive for Dart FFI lookups.
    names=sorted(set(re.findall(r'\bfisica_core_\w+(?=\()',(ROOT/'native/include/fisica_core.h').read_text())))
    return ' '.join('-Wl,-u,_'+name for name in names)

def podspecs():
    result={}
    for platform in ('ios','macos'):
        path=ROOT/'wrappers/flutter'/platform/'fisica_core.podspec'
        result[path]=re.sub(r"'OTHER_LDFLAGS' => '[^']*'","'OTHER_LDFLAGS' => '$(inherited) "+retained_symbols()+"'",path.read_text())
    return result

def outputs():
    """Every file this tool owns, with the text it should have."""
    project=ROOT/'wrappers/dotnet/Fisica.Scale.csproj'
    version=json.loads((ROOT/'wrappers/dotnet/wrapper.json').read_text())['version']
    return {**generated(),**podspecs(),
            project: re.sub(r'<Version>[^<]+</Version>', '<Version>'+version+'</Version>', project.read_text())}

def sync(check=False):
    """Rewrite the files that differ (with check, none); returns them."""
    stale={path:text for path,text in outputs().items() if not path.is_file() or path.read_text()!=text}
    if not check:
        for path,text in stale.items(): path.write_text(text)
    return list(stale)

def main(argv=None):
    parser=argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument('--check',action='store_true',help='write nothing; exit 1 when a generated file differs')
    args=parser.parse_args(argv)
    stale=sync(check=args.check)
    for path in stale: print(('stale: ' if args.check else 'updated: ')+path.relative_to(ROOT).as_posix())
    return 1 if args.check and stale else 0

if __name__=='__main__': sys.exit(main())
