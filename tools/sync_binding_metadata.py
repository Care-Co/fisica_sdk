"""Generate public wrapper constants; private algorithms are never copied."""
import json
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
def sync():
    sdk=json.loads((ROOT/'sdk-release.json').read_text())['sdk_version']
    for name in ('swift','kotlin','dotnet'):
        version=json.loads((ROOT/'wrappers'/name/'wrapper.json').read_text())['version']
        if name=='swift':
            path=ROOT/'wrappers/swift/Sources/FisicaScale/Release.swift'
            text=f'// Generated by tools/sync_binding_metadata.py\npublic enum FisicaRelease {{ public static let sdkVersion = "{sdk}"; public static let wrapperVersion = "{version}" }}\n'
        elif name=='kotlin':
            path=ROOT/'wrappers/kotlin/src/main/kotlin/com/carenco/fisica/Release.kt'
            text=f'// Generated by tools/sync_binding_metadata.py\npackage com.carenco.fisica\nobject FisicaRelease {{ const val SDK_VERSION = "{sdk}"; const val WRAPPER_VERSION = "{version}" }}\n'
        else:
            path=ROOT/'wrappers/dotnet/Release.cs'
            text=f'// Generated by tools/sync_binding_metadata.py\nnamespace CareCo.Fisica;\npublic static class FisicaRelease {{ public const string SdkVersion = "{sdk}"; public const string WrapperVersion = "{version}"; }}\n'
        path.write_text(text)
        if name=='dotnet':
            import re
            project=ROOT/'wrappers/dotnet/Fisica.Scale.csproj'
            project.write_text(re.sub(r'<Version>[^<]+</Version>', '<Version>'+version+'</Version>', project.read_text()))
if __name__=='__main__': sync()
